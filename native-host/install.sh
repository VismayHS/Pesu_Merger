#!/usr/bin/env bash
# Registers the PESU Downloader converter helper (native messaging host) for the current user
# on macOS and Linux. No sudo needed. Safe to run again at any time (e.g. after moving the folder).
#   ./install.sh                 # default extension id
#   ./install.sh <extension-id>  # if you changed the extension's key
set -euo pipefail

EXT_ID="${1:-cooigkfjkkbolfcfcdmbmdjpmbmlofab}"
HOST_NAME="com.pesu.downloader"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

c_ok=$'\033[32m'; c_warn=$'\033[33m'; c_err=$'\033[31m'; c_info=$'\033[36m'; c_off=$'\033[0m'
echo "${c_info}PESU Downloader - installing converter helper${c_off}"

# 1. Python 3.8+ (absolute path: browsers start the host with a minimal PATH)
PY=""
for cand in python3 python /opt/homebrew/bin/python3 /usr/local/bin/python3 /usr/bin/python3; do
  if command -v "$cand" >/dev/null 2>&1; then
    p="$(command -v "$cand")"
    if "$p" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1; then
      PY="$("$p" -c 'import sys; print(sys.executable)')"
      break
    fi
  fi
done
if [ -z "$PY" ]; then
  echo "${c_err}Python 3.8+ was not found.${c_off}"
  case "$(uname -s)" in
    Darwin) echo "  Install it with:  brew install python   (or from https://www.python.org/downloads/)";;
    *)      echo "  Install it with your package manager, e.g.:  sudo apt install python3";;
  esac
  exit 1
fi
echo "  Python:      $PY"

# 2. Optional PDF repair library (best effort, never fatal)
if ! "$PY" -c 'import pypdf' >/dev/null 2>&1; then
  echo "  Installing pypdf (optional, repairs damaged/locked PDFs)..."
  "$PY" -m pip install --user --quiet pypdf >/dev/null 2>&1 \
    || "$PY" -m pip install --user --quiet --break-system-packages pypdf >/dev/null 2>&1 \
    || echo "  ${c_warn}(skipped - optional)${c_off}"
fi

# 3. Launcher + host manifest
LAUNCHER="$HERE/run_host.sh"
cat > "$LAUNCHER" <<EOF
#!/bin/sh
# Generated by install.sh - starts the PESU Downloader helper.
exec "$PY" -u "$HERE/pesu_host.py" "\$@"
EOF
chmod +x "$LAUNCHER" "$HERE/pesu_host.py"

esc() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
MANIFEST_JSON=$(cat <<EOF
{
  "name": "$HOST_NAME",
  "description": "PESU Downloader converter helper",
  "path": "$(esc "$LAUNCHER")",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
EOF
)

# 4. Register for every Chromium-based browser we know about
if [ "$(uname -s)" = "Darwin" ]; then
  B="$HOME/Library/Application Support"
  DIRS=(
    "$B/Google/Chrome" "$B/Google/Chrome Beta" "$B/Google/Chrome Canary" "$B/Chromium"
    "$B/BraveSoftware/Brave-Browser" "$B/Microsoft Edge" "$B/Vivaldi" "$B/Arc/User Data"
  )
else
  C="${XDG_CONFIG_HOME:-$HOME/.config}"
  DIRS=(
    "$C/google-chrome" "$C/google-chrome-beta" "$C/google-chrome-unstable" "$C/chromium"
    "$C/BraveSoftware/Brave-Browser" "$C/microsoft-edge" "$C/vivaldi"
  )
fi
installed=0
for d in "${DIRS[@]}"; do
  # Install where the browser exists; always install for Google Chrome so a later install works too.
  if [ -d "$d" ] || [ "$d" = "${DIRS[0]}" ]; then
    mkdir -p "$d/NativeMessagingHosts"
    printf '%s\n' "$MANIFEST_JSON" > "$d/NativeMessagingHosts/$HOST_NAME.json"
    echo "  Registered:  $d"
    installed=$((installed + 1))
  fi
done
printf '%s\n' "$MANIFEST_JSON" > "$HERE/$HOST_NAME.json"

# 5. Self-test: start the helper and ask it what it can do
INFO="$("$PY" - "$LAUNCHER" <<'PYEOF' 2>/dev/null || true
import json, struct, subprocess, sys
p = subprocess.Popen([sys.argv[1]], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
m = json.dumps({"id": 1, "op": "ping", "meta": {}, "chunks": 0}).encode()
p.stdin.write(struct.pack("<I", len(m)) + m); p.stdin.flush()
n = struct.unpack("<I", p.stdout.read(4))[0]
r = json.loads(p.stdout.read(n)); p.kill()
meta = r.get("meta") or {}
print("OK" if r.get("ok") else "FAIL", meta.get("libreoffice") or "")
PYEOF
)"
case "$INFO" in
  OK*) echo "  Self-test:   ${c_ok}helper answers correctly${c_off}";;
  *)   echo "  Self-test:   ${c_warn}could not talk to the helper (see ~/.cache/pesu-downloader/host.log)${c_off}";;
esac
LO="${INFO#OK }"; LO="${LO#OK}"
if [ -n "$LO" ] && [ "${INFO%% *}" = "OK" ]; then
  echo "  LibreOffice: $LO"
else
  echo "  ${c_warn}LibreOffice: not found${c_off} - PDFs will still merge, but PPT/DOC files need LibreOffice to become PDFs."
  case "$(uname -s)" in
    Darwin) echo "               Install:  brew install --cask libreoffice   (or https://www.libreoffice.org/download/)";;
    *)      echo "               Install:  sudo apt install libreoffice-impress libreoffice-writer libreoffice-calc  (or your distro's equivalent)";;
  esac
fi
echo
echo "${c_ok}Done.${c_off} Reload the extension page (or restart the browser) and press Re-check."
